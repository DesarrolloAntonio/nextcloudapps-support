#!/usr/bin/env python3
"""Fill in everything that needs the site's absolute URL.

The base URL lives in ONE place: "base_url" in site.json. To move the site (for example to a
subdomain), change that line and run:

    python3 tools/build.py

It rewrites, from site.json:
  - the block between <!-- site-head:start --> and <!-- site-head:end --> in every page that has
    a "file": title, meta description, canonical, Open Graph, Twitter card and, on the home page,
    the schema.org SoftwareApplication JSON-LD;
  - every <a data-site-url>, a visible link to the site (used on the press page);
  - sitemap.xml and robots.txt.

Everything else in the pages uses relative links, so nothing else changes when the URL does.
Only the Python standard library is needed.
"""
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
START = "<!-- site-head:start (generated by tools/build.py from site.json; edit there) -->"
END = "<!-- site-head:end -->"
BLOCK = re.compile(r"<!-- site-head:start[^>]*-->.*?<!-- site-head:end -->", re.S)
SITE_LINK = re.compile(r"<a data-site-url[^>]*>.*?</a>", re.S)


def attr(value):
    return html.escape(str(value), quote=True)


def head_block(site, page, base):
    url = base + page["path"]
    image = base + site["og_image"]
    og_title = page.get("og_title", page["title"])
    lines = [
        START,
        f"<title>{html.escape(page['title'])}</title>",
        f'<meta name="description" content="{attr(page["description"])}">',
        f'<link rel="canonical" href="{attr(url)}">',
        '<meta property="og:type" content="website">',
        f'<meta property="og:site_name" content="{attr(site["site_name"])}">',
        f'<meta property="og:title" content="{attr(og_title)}">',
        f'<meta property="og:description" content="{attr(page["description"])}">',
        f'<meta property="og:url" content="{attr(url)}">',
        f'<meta property="og:image" content="{attr(image)}">',
        f'<meta property="og:image:width" content="{site["og_image_width"]}">',
        f'<meta property="og:image:height" content="{site["og_image_height"]}">',
        f'<meta property="og:image:alt" content="{attr(site["og_image_alt"])}">',
        '<meta property="og:locale" content="en_US">',
        '<meta name="twitter:card" content="summary_large_image">',
        f'<meta name="twitter:title" content="{attr(og_title)}">',
        f'<meta name="twitter:description" content="{attr(page["description"])}">',
        f'<meta name="twitter:image" content="{attr(image)}">',
        f'<meta name="twitter:image:alt" content="{attr(site["og_image_alt"])}">',
    ]
    if page.get("software_application"):
        data = {
            "@context": "https://schema.org",
            "@type": "SoftwareApplication",
            "name": site["site_name"],
            "description": page["description"],
            "url": url,
            "image": image,
            "screenshot": [
                base + "assets/img/deck.webp",
                base + "assets/img/notes.webp",
                base + "assets/img/news.webp",
                base + "assets/img/bookmarks.webp",
                base + "assets/img/tablet.webp",
            ],
            "operatingSystem": "Android",
            "softwareRequirements": "Android 12 or later",
            "applicationCategory": "ProductivityApplication",
            "installUrl": site["play_url"],
            "downloadUrl": site["play_url"],
            "isAccessibleForFree": True,
            "offers": {"@type": "Offer", "price": 0, "priceCurrency": "EUR"},
        }
        text = json.dumps(data, indent=2, ensure_ascii=False).replace("</", "<\\/")
        lines.append('<script type="application/ld+json">')
        lines.append(text)
        lines.append("</script>")
    lines.append(END)
    return "\n".join(lines)


def main():
    site = json.loads((ROOT / "site.json").read_text(encoding="utf-8"))
    base = site["base_url"].strip()
    if not re.match(r"^https://[^/]+/(.+/)?$", base):
        sys.exit(f"site.json: base_url must start with https:// and end with '/': {base!r}")

    for page in site["pages"]:
        if "file" not in page:
            continue
        path = ROOT / page["file"]
        text = path.read_text(encoding="utf-8")
        if not BLOCK.search(text):
            sys.exit(f"{page['file']}: no site-head block to fill in")
        text = BLOCK.sub(lambda _m: head_block(site, page, base), text, count=1)
        # Visible links to the site itself: <a data-site-url ...>...</a> gets the base URL as href and text.
        shown = re.sub(r"^https://|/$", "", base)
        text = SITE_LINK.sub(
            lambda _m: f'<a data-site-url href="{attr(base)}">{html.escape(shown)}</a>', text
        )
        path.write_text(text, encoding="utf-8")
        print(f"head      {page['file']}")

    urls = []
    for page in site["pages"]:
        entry = f"  <url>\n    <loc>{html.escape(base + page['path'])}</loc>\n"
        if page.get("lastmod"):
            entry += f"    <lastmod>{page['lastmod']}</lastmod>\n"
        urls.append(entry + "  </url>")
    sitemap = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "\n".join(urls)
        + "\n</urlset>\n"
    )
    (ROOT / "sitemap.xml").write_text(sitemap, encoding="utf-8")
    print("written   sitemap.xml")

    robots = f"User-agent: *\nAllow: /\n\nSitemap: {base}sitemap.xml\n"
    (ROOT / "robots.txt").write_text(robots, encoding="utf-8")
    print("written   robots.txt")


if __name__ == "__main__":
    main()
